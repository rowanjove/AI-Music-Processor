class WorkerRecoveryTests(unittest.TestCase):
    def test_success_sidecar_preserves_actual_terminal_inference_identity(self):
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory) / 'result.wav'
            terminal = {'worker': 'rvc', 'status': 'complete', 'device': 'cpu',
                        'actual_f0': 'harvest', 'validation_seed': None,
                        'output_precision': 'legacy_int16',
                        'model_guard': {'complete_weight_shapes_verified': True}}
            def run(command, **kwargs):
                output.write_bytes(b'new output')
                return CompletedProcess(command, 0, ('log\n' + json.dumps(terminal) + '\n').encode(), b'')
            result = run_worker_with_recovery(['worker.py', '--device', 'cpu'], [output],
                                             timeout=10, run_fn=run,
                                             sidecar_path=str(output) + '.worker.json')
            saved = json.loads(Path(str(output) + '.worker.json').read_text(encoding='utf-8'))
            self.assertEqual(saved['terminal_worker_result'], terminal)
            self.assertEqual(result.worker_metadata['terminal_worker_result'], terminal)
            output.unlink()
            def opaque_run(command, **kwargs):
                output.write_bytes(b'new output')
                return CompletedProcess(command, 0, b'no structured inference record', b'')
            result = run_worker_with_recovery(['worker.py', '--device', 'cpu'], [output],
                                             timeout=10, run_fn=opaque_run)
            self.assertNotIn('terminal_worker_result', result.worker_metadata)

    def test_old_existing_output_cannot_count_as_success(self):
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory)/'old.wav';output.write_bytes(b'old valid output')
            def fake_run(command, **kwargs):return CompletedProcess(command,0,b'',b'')
            with self.assertRaisesRegex(RuntimeError,'not generated by this attempt'):
                run_worker_with_recovery(['worker.py'],[str(output)],timeout=10,run_fn=fake_run)
            self.assertEqual(output.read_bytes(),b'old valid output')
    def test_cuda_oom_retries_reduced_gpu_then_cpu(self):
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory) / 'result.wav'
            calls = []

            def fake_run(command, **kwargs):
                args = list(command)
                device = args[args.index('--device') + 1]
                calls.append(args)
                if device != 'cpu':
                    return CompletedProcess(args, 1, b'', b'worker_error CUDA out of memory')
                output.write_bytes(b'complete')
                return CompletedProcess(args, 0, b'', b'')

            result = run_worker_with_recovery(
                ['worker.py', '--device', 'auto', '--segment', '6'],
                [str(output)],
                timeout=10,
                gpu_overrides={'segment': 3},
                sidecar_path=str(output) + '.worker.json',
                run_fn=fake_run,
            )
            self.assertEqual(result.returncode, 0)
            self.assertEqual([c[c.index('--device') + 1] for c in calls], ['auto', 'cuda', 'cpu'])
            self.assertIn('--segment', calls[1])
            self.assertEqual(calls[1][calls[1].index('--segment') + 1], '3')
            self.assertTrue(output.is_file())
            self.assertTrue(Path(str(output) + '.worker.json').is_file())
            self.assertEqual(result.recovery_attempts[-1]['device'], 'cpu')
            self.assertEqual(result.recovery_attempts[0]['category'], 'cuda_oom')

    def test_non_oom_failure_is_not_retried(self):
        calls = []

        def fake_run(command, **kwargs):
            calls.append(list(command))
            return CompletedProcess(command, 1, b'', b'checkpoint missing')

        with self.assertRaisesRegex(RuntimeError, 'checkpoint missing'):
            run_worker_with_recovery(['worker.py'], [], timeout=10, run_fn=fake_run)
        self.assertEqual(len(calls), 1)

    def test_structured_non_oom_category_overrides_oom_text(self):
        calls = []

        def fake_run(command, **kwargs):
            calls.append(list(command))
            return CompletedProcess(command, 1, b'',
                                    b'{"worker_error":{"category":"worker_error","phase":"model_load","message":"CUDA out of memory"}}')

        with self.assertRaises(RuntimeError):
            run_worker_with_recovery(['worker.py'], [], timeout=10, run_fn=fake_run)
        self.assertEqual(len(calls), 1)

    def test_explicit_cpu_does_not_probe_gpu(self):
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory) / 'result.wav'
            calls = []

            def fake_run(command, **kwargs):
                calls.append((list(command), kwargs['timeout']))
                output.write_bytes(b'complete')
                return CompletedProcess(command, 0, b'{"worker":"fake","device":"cpu"}', b'')

            result = run_worker_with_recovery(
                ['worker.py', '--device', 'cpu'], [str(output)], timeout=10,
                gpu_overrides={'segment': 3}, run_fn=fake_run,
            )
            self.assertEqual(result.returncode, 0)
            self.assertEqual(len(calls), 1)
            self.assertEqual(calls[0][0][calls[0][0].index('--device') + 1], 'cpu')
            self.assertEqual(result.recovery_attempts[0]['device'], 'cpu')

    def test_oom_detection_does_not_match_generic_memory_error(self):
        self.assertTrue(is_cuda_oom('RuntimeError: CUDA out of memory.'))
        self.assertTrue(is_cuda_oom('CUBLAS_STATUS_ALLOC_FAILED'))
        self.assertFalse(is_cuda_oom('MemoryError: unable to allocate buffer'))

    def test_rvc_worker_main_writes_readable_wav_with_part_suffix(self):
        """Exercise the worker entrypoint with fake inference and real soundfile IO."""
        import contextlib
        import numpy as np
        import soundfile as sf

        class FakeTensor:
            shape = (1,)

        class FakeModel:
            def __init__(self, *args, **kwargs):
                self.enc_q = object()

            def load_state_dict(self, *args, **kwargs):
                return self

            def eval(self):
                return self

            def to(self, *args, **kwargs):
                return self

            def float(self):
                return self

        class FakeCuda:
            @staticmethod
            def is_available():
                return False

            @staticmethod
            def empty_cache():
                pass

            @staticmethod
            def ipc_collect():
                pass

        class FakeTorch:
            cuda = FakeCuda()

            @staticmethod
            def set_num_threads(_value):
                pass

            @staticmethod
            def load(_path, map_location=None):
                return {'config': [1, 2, 3, 16000], 'weight': {'emb_g.weight': FakeTensor()},
                        'version': 'v1', 'f0': 0}

            @staticmethod
            @contextlib.contextmanager
            def inference_mode():
                yield

        class FakeVC:
            def __init__(self, *_args):
                pass

            def pipeline(self, *_args):
                return np.linspace(-.2, .2, 1600, dtype='float32')

        checkpoint_utils = types.ModuleType('fairseq.checkpoint_utils')
        checkpoint_utils.load_model_ensemble_and_task = lambda *_args: [[FakeModel()]]
        fairseq = types.ModuleType('fairseq')
        fairseq.checkpoint_utils = checkpoint_utils
        vc_module = types.ModuleType('vc_infer_pipeline')
        vc_module.VC = FakeVC
        infer_pack = types.ModuleType('infer_pack')
        models_module = types.ModuleType('infer_pack.models')
        for name in ('SynthesizerTrnMs256NSFsid', 'SynthesizerTrnMs256NSFsid_nono',
                     'SynthesizerTrnMs768NSFsid', 'SynthesizerTrnMs768NSFsid_nono'):
            setattr(models_module, name, FakeModel)
        infer_pack.models = models_module
        utils_module = types.ModuleType('my_utils')
        utils_module.load_audio = lambda *_args: np.ones(1600, dtype='float32')
        saved_modules = {name: sys.modules.get(name) for name in
                         ('torch', 'fairseq', 'fairseq.checkpoint_utils', 'vc_infer_pipeline', 'infer_pack', 'infer_pack.models', 'my_utils')}
        original_argv = sys.argv[:]
        original_cwd = os.getcwd()
        try:
            sys.modules.update({'torch': FakeTorch, 'fairseq': fairseq,
                               'fairseq.checkpoint_utils': checkpoint_utils,
                               'vc_infer_pipeline': vc_module, 'infer_pack': infer_pack,
                               'infer_pack.models': models_module, 'my_utils': utils_module})
            import core.rvc_worker as worker
            with tempfile.TemporaryDirectory() as directory:
                output = os.path.join(directory, 'result.wav')
                sys.argv = ['rvc_worker.py', '--input', os.path.join(directory, 'input.wav'),
                            '--output', output, '--model', os.path.join(directory, 'model.pth'),
                            '--device', 'cpu']
                # This test isolates real FLOAT-WAV/temporary-file IO. The
                # data-only checkpoint and semantic guards have separate real
                # adversarial tests; no unsafe fallback is allowed in workers.
                from unittest import mock
                with mock.patch.object(worker, 'load_voice_checkpoint', return_value=FakeTorch.load('fixture')), \
                     mock.patch('core.safe_checkpoint.validate_rvc_inference_checkpoint', return_value={}):
                    worker.main()
                samples, sample_rate = sf.read(output, dtype='float32')
                self.assertEqual(sample_rate, 16000)
                self.assertEqual(len(samples), 1600)
                self.assertTrue(np.isfinite(samples).all())
        finally:
            os.chdir(original_cwd)
            sys.argv = original_argv
            for name, module in saved_modules.items():
                if module is None:
                    sys.modules.pop(name, None)
                else:
                    sys.modules[name] = module

    def test_rvc_worker_rejects_zero_x_pad(self):
        import core.rvc_worker as worker
        original_argv = sys.argv[:]
        try:
            sys.argv = ['rvc_worker.py', '--input', 'in.wav', '--output', 'out.wav',
                        '--model', 'model.pth', '--x-pad', '0']
            with self.assertRaises(SystemExit):
                worker.main()
        finally:
            sys.argv = original_argv


class ProcessCaptureTests(unittest.TestCase):
    def test_process_capture_is_bounded(self):
        import sys

        code = 'import sys; sys.stdout.write("x"*600000); sys.stderr.write("y"*600000)'
        result = Control().run([sys.executable, '-c', code], timeout=30, check=False)
        self.assertLessEqual(len(result.stdout or b''), 256 * 1024)
        self.assertLessEqual(len(result.stderr or b''), 256 * 1024)


